def load(program, robot):

    @program(1, "setup")
    def setupmotor():
        robot.motor_target(robot.right_motor, 300, 45)
        robot.motor_target(robot.left_motor, 300, 0)
        robot.wait(2000)

    @program(2, "betterGamble")
    def bettergamble():
        robot.reset_drivebase_settings()

        robot.set_drivebase_settings(600)
        robot.set_drivebase_settings(straight_speed=800)
        robot.set_gyro_use(True)
        robot.straight(-10)
        robot.reset_heading(0)
        robot.set_gyro_use(True)

        robot.reset_heading(0)
        robot.straight(850)
        robot.motor_angle(robot.right_motor, 300, -300)
        robot.straight(60)
        robot.motor_angle(robot.right_motor, 800, -360)
        robot.motor_angle(robot.right_motor, 800, 300)
        robot.straight(-250)
        robot.turn(90)
        robot.straight(310)
        robot.turn(-90)
        robot.set_drivebase_settings(600)
        robot.straight(90, precise=False)
        robot.set_drivebase_settings(800)
        robot.wait(300)
        robot.straight(250, precise=False)
        robot.straight(-170)
        robot.turn(-140)
        robot.straight(550)

    @program(3, "DerErsteRun?!")
    def route_program():
        robot.set_gyro_use(True)
        robot.set_drivebase_settings(800)
        robot.straight(410)
        robot.straight(-410)
        robot.straight(30)
        robot.turn(46)
        robot.motor_until_stalled(robot.right_motor, -300)
        robot.straight(540)
        robot.motor_angle(robot.right_motor, speed=300, angle=130)
        robot.set_drivebase_settings(straight_speed=800)
        robot.straight(-500)

    @program(4, "Drohnenfiech")
    def drohnenfiech():
        robot.set_gyro_use(True)
        robot.set_drivebase_settings(450)
        robot.reset_heading(0)
        robot.straight(720)
        robot.turn(-30)
        robot.straight(10)
        robot.turn(-20)
        robot.turn(50)
        robot.straight(-180)
        robot.turn(-50)
        robot.straight(630)
        robot.turn(-35)
        robot.straight(85)
        robot.turn(65)
        robot.straight(-30)
        robot.turn(13)
        robot.set_drivebase_settings(800)
        robot.straight(20)
        robot.reset_drivebase_settings()
        robot.motor_angle(robot.right_motor, 300, 100)
        robot.straight(-80)
        robot.motor_angle(robot.left_motor, 300, -60)
        robot.motor_angle(robot.right_motor, 300, -100)
        robot.straight(65)
        robot.motor_angle(robot.left_motor, 300, 60)
        robot.straight(-30)
        robot.turn(-42)
        robot.straight(250)
        robot.set_drivebase_settings(80)
        robot.straight(140)
        robot.straight(-65)
        robot.turn(-100)

    @program(5, "weisses Ding")
    def route_program():
        robot.motor_target(robot.right_motor, 500, -10)
        robot.wait(5000)
        robot.set_drivebase_settings(550)
        robot.straight(-10)
        robot.reset_heading(0)
        robot.straight(800)
        robot.straight(-80)
        robot.straight(50)
        robot.wait(200)
        robot.straight(-20)
        robot.turn(135)
        robot.straight(-150)
        robot.turn(-50)
        robot.straight(215)
        robot.turn(-10)
        robot.motor_angle(robot.right_motor, 600, -60)
        robot.turn(20)
        robot.turn(-10)
        robot.motor_angle(robot.right_motor, 600, 60)
        robot.straight(-180)
        robot.turn(70)
        robot.straight(680)

    @program(6, "tjostenFragezeichen")
    def ziehDing():
        robot.set_drivebase_settings(1000)
        robot.straight(400)
        robot.multitask(robot.motor_angle_task(robot.right_motor, 300, -30), robot.motor_angle_task(robot.left_motor, 300, 30))
        # hier den Samen einsammeln !!!!
        robot.straight(-100)
        robot.multitask(robot.straight_task(-300), robot.motor_angle_task(robot.right_motor, 100, 30), robot.motor_angle_task(robot.left_motor, 100, -30))
        robot.wait(500)
        robot.straight(-300)


    @program(7, "raushebeding")
    def raushebeding():
        robot.set_drivebase_settings(1000)
        robot.straight(450)
        robot.set_drivebase_settings(40)
        robot.straight(-50)
        robot.multitask(robot.motor_angle_task(robot.right_motor,-300, 120), robot.motor_angle_task(robot.left_motor,-300, -120))
        robot.reset_drivebase_settings()
        robot.straight(-400)
        robot.multitask(robot.motor_angle_task(robot.right_motor,-300, -120), robot.motor_angle_task(robot.left_motor,-300, 120))

    @program(8, "altePalme")
    def altePalme():
        robot.motor_target(robot.right_motor, 600, 0)
        robot.motor_target(robot.left_motor, 600, 0)
        robot.wait(3000)
        robot.set_gyro_use(True)
        robot.reset_heading(0)
        robot.reset_drivebase_settings()
        robot.set_drivebase_settings(800)
        robot.straight(450)
        robot.turn(-45)
        robot.straight(205)
        robot.turn(90)
        robot.straight(250)
        robot.motor_angle(robot.left_motor, 600, 90)
        robot.straight(-20)
        robot.motor_angle(robot.left_motor, 600, -90)
        robot.straight(50)
        robot.motor_angle(robot.right_motor, 600, 160)
        robot.motor_angle(robot.right_motor, 600, -160)
        robot.straight(-200)
        robot.turn(-60)
        robot.straight(-700)
